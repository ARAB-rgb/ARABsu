/**
 * Smart place holder replacements inside contracts and clauses
 */
export function replaceSmartVariables(text: string, c: Partial<Subcontract>): string {
  if (!text) return "";
  let res = text;
  
  const map: Record<string, string> = {
    "{{رقم_العقد}}": c.contract_no || "لم يحدد",
    "{{عنوان_العقد}}": c.title || "عقد مقاولة من الباطن",
    "{{اسم_المشروع}}": c.project_name || "لم يحدد",
    "{{مالك_المشروع}}": c.project_owner || "لم يحدد",
    "{{موقع_المشروع}}": c.project_location || "لم يحدد",
    "{{المقاول_الرئيسي}}": c.main_contractor || "شركة عرب وورلد للمقاولات",
    "{{اسم_الطرف_الأول}}": c.first_party?.legal_name || "شركة عرب وورلد للمقاولات العامة",
    "{{سجل_الطرف_الأول}}": c.first_party?.cr_number || "---",
    "{{ضريبة_الطرف_الأول}}": c.first_party?.tax_number || "---",
    "{{ممثل_الطرف_الأول}}": c.first_party?.representative_name || "---",
    "{{صفة_ممثل_الطرف_الأول}}": c.first_party?.representative_title || "---",
    "{{اسم_الطرف_الثاني}}": c.second_party?.legal_name || "---",
    "{{سجل_الطرف_الثاني}}": c.second_party?.cr_number || "---",
    "{{ضريبة_الطرف_الثاني}}": c.second_party?.tax_number || "---",
    "{{ممثل_الطرف_الثاني}}": c.second_party?.representative_name || "---",
    "{{صفة_ممثل_الطرف_الثاني}}": c.second_party?.representative_title || "---",
    "{{جوال_الطرف_الثاني}}": c.second_party?.phone || "---",
    "{{ايبان_الطرف_الثاني}}": c.second_party?.iban || "---",
    "{{بنك_الطرف_الثاني}}": c.second_party?.bank_name || "---",
    "{{مدة_التنفيذ}}": c.duration_days ? `${c.duration_days} يوماً` : "---",
    "{{تاريخ_البدء}}": c.commencement_date || "---",
    "{{تاريخ_الانتهاء}}": c.completion_date || "---",
    "{{إجمالي_المبلغ}}": c.total_amount ? `${c.total_amount.toLocaleString()} ريال` : "---",
    "{{نسبة_المحتجز}}": c.retention_pct ? `${c.retention_pct}%` : "5%",
    "{{المهندس_المشرف}}": c.supervising_engineer || "مهندس المشروع المعتمد",
  };

  Object.entries(map).forEach(([token, val]) => {
    res = res.split(token).join(val);
  });

  return res;
}

/**
 * Generate sequential Contract Number
 */
export function generateSubcontractNumber(existingCount: number): string {
  const year = new Date().getFullYear();
  const seq = String(existingCount + 1).padStart(4, "0");
  return `AW-SUB-${year}-${seq}`;
}
